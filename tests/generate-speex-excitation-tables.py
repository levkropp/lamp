#!/usr/bin/env python3
"""Extract pinned BSD Speex pitch/innovation books without runtime C."""
import argparse
import importlib.util
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parent.parent
BOOKS=[('gain_table.c','gain_cdbk_nb',512),('gain_table_lbr.c','gain_cdbk_lbr',128),('exc_10_16_table.c','exc_10_16_table',160),('exc_20_32_table.c','exc_20_32_table',640),('exc_10_32_table.c','exc_10_32_table',320),('exc_5_64_table.c','exc_5_64_table',320),('exc_8_128_table.c','exc_8_128_table',1024),('exc_5_256_table.c','exc_5_256_table',1280),('hexc_10_32_table.c','hexc_10_32_table',320),('hexc_table.c','hexc_table',1024)]

def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 spec=importlib.util.spec_from_file_location('speex_reference',ROOT/'tests/build-speex-reference.py');reference=importlib.util.module_from_spec(spec);spec.loader.exec_module(reference);source,_,_=reference.prepare()
 lines=['# Generated by tests/generate-speex-excitation-tables.py; Speex 1.2.1.',f'# Source archive SHA-256: {reference.SHA256}','# Copyright (C) 2002 Jean-Marc Valin. Original BSD notices, including','# the separate author-form table notices, are in THIRD_PARTY_NOTICES.']
 for filename,name,size in BOOKS:
  text=(source/'libspeex'/filename).read_text();match=re.search(r'const signed char\s+'+re.escape(name)+r'\[(\d+)\]\s*=\s*\{([^}]+)\}',text,re.S)
  if not match or int(match[1])!=size:raise RuntimeError('Speex excitation declaration changed: '+name)
  data=[int(n) for n in re.findall(r'-?\d+',match[2])]
  if len(data)!=size or any(x< -128 or x>127 for x in data):raise RuntimeError('Speex excitation values changed: '+name)
  lines+=['.p2align 4','spx_'+name+':'];lines+=['    .byte '+', '.join(map(str,data[i:i+16])) for i in range(0,size,16)]
 result='\n'.join(lines)+'\n';target=ROOT/'src/speex_excitation_tables.inc'
 if args.check:
  if not target.exists() or target.read_text()!=result:raise RuntimeError('Speex excitation tables need regeneration')
  print(f'Speex excitation books match {sum(x[2] for x in BOOKS)} pinned signed-byte values.')
 else:target.write_text(result,encoding='utf-8',newline='\n');print(target)
if __name__=='__main__':main()

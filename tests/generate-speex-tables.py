#!/usr/bin/env python3
"""Generate Speex LSP books from checksum-pinned BSD Speex 1.2.1 sources."""
import argparse
import importlib.util
from pathlib import Path
import re
import sys
ROOT=Path(__file__).resolve().parent.parent

def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 spec=importlib.util.spec_from_file_location('speex_reference',ROOT/'tests/build-speex-reference.py');reference=importlib.util.module_from_spec(spec);spec.loader.exec_module(reference);source,_,_=reference.prepare()
 names=[('lsp_tables_nb.c',name,size) for name,size in [('cdbk_nb',640),('cdbk_nb_low1',320),('cdbk_nb_low2',320),('cdbk_nb_high1',320),('cdbk_nb_high2',320)]]+[('high_lsp_tables.c',name,512) for name in ['high_lsp_cdbk','high_lsp_cdbk2']]
 lines=['# Generated by tests/generate-speex-tables.py from Speex 1.2.1.',f'# Source archive SHA-256: {reference.SHA256}','# Copyright (C) 2002 Jean-Marc Valin. BSD-3-Clause author license;','# full original notice retained in THIRD_PARTY_NOTICES. Do not edit.']
 for filename,name,size in names:
  text=(source/'libspeex'/filename).read_text();match=re.search(r'const signed char\s+'+re.escape(name)+r'\[(\d+)\]\s*=\s*\{([^}]+)\}',text,re.S)
  if not match or int(match[1])!=size:raise RuntimeError('Speex table declaration changed: '+name)
  values=[int(n) for n in re.findall(r'-?\d+',match[2])]
  if len(values)!=size or any(n< -128 or n>127 for n in values):raise RuntimeError('Speex table values changed: '+name)
  lines+=['.p2align 4','spx_'+name+':']
  lines+=['    .byte '+', '.join(map(str,values[i:i+16])) for i in range(0,size,16)]
 result='\n'.join(lines)+'\n';target=ROOT/'src/speex_lsp_tables.inc'
 if args.check:
  if not target.exists() or target.read_text()!=result:raise RuntimeError('Speex LSP tables need regeneration')
  print('Speex LSP books match all 2,944 pinned signed-byte coefficients.')
 else:target.write_text(result,encoding='utf-8',newline='\n');print(target)
if __name__=='__main__':main()
